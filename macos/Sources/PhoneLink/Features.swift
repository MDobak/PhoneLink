import AppKit
import AVFoundation

/// Skips items that apps mark as concealed or transient, such as passwords.
final class ClipboardSync {
    static let shared = ClipboardSync()
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let skipTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword"),
    ]

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
    }

    private func tick() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard UserDefaults.standard.bool(forKey: "shareClipboard"), PhoneLink.shared.state == .connected else { return }
        let types = Set(pb.types ?? [])
        guard types.isDisjoint(with: Self.skipTypes), !types.contains(.fileURL) else { return }
        if let s = pb.string(forType: .string), !s.isEmpty {
            if s.utf8.count < 1 << 20 { PhoneLink.shared.send(["t": "clip", "text": s]) }
            return
        }
        DispatchQueue.global(qos: .utility).async {
            guard let png = Self.png(from: pb), png.count < 8 << 20 else { return }
            PhoneLink.shared.send(["t": "clip", "image": png.base64EncodedString()])
        }
    }

    private static func png(from pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        guard let d = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: d) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    func received(_ j: JSON) {
        let pb = NSPasteboard.general
        if let t = j.str("text") {
            pb.clearContents()
            pb.setString(t, forType: .string)
        } else if let b = j.str("image"), let d = Data(base64Encoded: b) {
            pb.clearContents()
            pb.setData(d, forType: .png)
        } else { return }
        lastChange = pb.changeCount
    }
}

/// macOS keeps the active Focus in a file that needs Full Disk Access.
final class FocusSync {
    static let shared = FocusSync()
    private var timer: Timer?
    private var last: Bool?
    private let url = URL(fileURLWithPath: NSHomeDirectory() + "/Library/DoNotDisturb/DB/Assertions.json")

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 3, repeats: true) { [weak self] _ in self?.check() }
    }

    var canRead: Bool { focusOn() != nil }

    func focusOn() -> Bool? {
        guard let d = try? Data(contentsOf: url),
              let j = (try? JSONSerialization.jsonObject(with: d)) as? JSON else { return nil }
        let records = (j["data"] as? [JSON] ?? []).flatMap { ($0["storeAssertionRecords"] as? [Any]) ?? [] }
        return !records.isEmpty
    }

    func resend() { last = nil; check() }

    private func check() {
        guard UserDefaults.standard.bool(forKey: "focusSync"), PhoneLink.shared.sessionConnected, let on = focusOn() else { return }
        if on != last {
            last = on
            PhoneLink.shared.setDnd(on)
        }
    }
}

/// Plays phone audio during screen sharing: 48 kHz stereo 16-bit PCM in 20 ms chunks.
/// Keeps at most 250 ms queued so the sound stays in sync with the picture.
final class ScreenAudioPlayer {
    static let shared = ScreenAudioPlayer()
    private let engine = AVAudioEngine()
    private let node = AVAudioPlayerNode()
    private let format = AVAudioFormat(commonFormat: .pcmFormatFloat32, sampleRate: 48_000, channels: 2, interleaved: false)!
    private let q = DispatchQueue(label: "phonelink.audio")
    private var running = false
    /// Frames queued in the player node. Access on q.
    private var queued = 0
    /// Bumped on stop, so buffers from an old epoch do not change queued.
    private var epoch = 0

    private init() {
        engine.attach(node)
        engine.connect(node, to: engine.mainMixerNode, format: format)
    }

    func play(_ d: Data) {
        ScreenRecorder.shared.audio(d)
        q.async { [self] in
            guard UserDefaults.standard.bool(forKey: "screenSound") else { return }
            // macOS stops the engine when the output device changes. Restart with an empty queue.
            if running, !engine.isRunning { reset() }
            if !running {
                do { try engine.start() } catch { return }
                node.play()
                running = true
            }
            guard queued < 12_000 else { return }
            if queued == 0 { schedule(silence(2_880)) } // 60 ms of buffer against network jitter
            let frames = d.count / 4
            guard frames > 0, let buf = AVAudioPCMBuffer(pcmFormat: format, frameCapacity: AVAudioFrameCount(frames)) else { return }
            buf.frameLength = AVAudioFrameCount(frames)
            let l = buf.floatChannelData![0], r = buf.floatChannelData![1]
            d.withUnsafeBytes { raw in
                let s = raw.bindMemory(to: Int16.self)
                for i in 0..<frames {
                    l[i] = Float(Int16(littleEndian: s[2 * i])) / 32768
                    r[i] = Float(Int16(littleEndian: s[2 * i + 1])) / 32768
                }
            }
            schedule(buf)
        }
    }

    private func silence(_ frames: Int) -> AVAudioPCMBuffer {
        let b = AVAudioPCMBuffer(pcmFormat: format, frameCapacity: AVAudioFrameCount(frames))!
        b.frameLength = AVAudioFrameCount(frames)
        return b
    }

    private func schedule(_ b: AVAudioPCMBuffer) {
        let n = Int(b.frameLength)
        let e = epoch
        queued += n
        node.scheduleBuffer(b) { [weak self] in
            self?.q.async { if let self, self.epoch == e { self.queued -= n } }
        }
    }

    func stop() {
        q.async { [self] in
            if running { reset() }
        }
    }

    /// On q.
    private func reset() {
        node.stop()
        engine.stop()
        running = false
        queued = 0
        epoch += 1
    }
}

/// The "Send to Phone" service in the Services menu and in context menus of other apps.
final class ServiceProvider: NSObject {
    @objc func sendToPhone(_ pb: NSPasteboard, userData: String?, error: AutoreleasingUnsafeMutablePointer<NSString?>) {
        let link = PhoneLink.shared
        guard link.state == .connected else { error.pointee = "The phone is not connected." as NSString; return }
        let text = (pb.string(forType: .URL) ?? pb.string(forType: .string) ?? "").trimmingCharacters(in: .whitespacesAndNewlines)
        if let u = URL(string: text), ["http", "https"].contains(u.scheme?.lowercased() ?? ""), !text.contains(" ") {
            link.openOnPhone(u)
        } else if !text.isEmpty {
            link.send(["t": "clip", "text": text])
        }
    }
}
